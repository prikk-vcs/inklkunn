#!/usr/bin/env python3
"""Regenerate the lock inventory appendix of docs/dependency-policy.md from Cargo.lock and `cargo tree`.

Each non-workspace crate is attributed to the workspace crate(s) and the direct dependency that pull it in,
so that the ledger's accepted rows (by direct dependency) and the inventory (by crate) stay derivable from
each other. Dev-only and build-only crates are marked. Run from the workspace root; the test
`tools/pin-check/tests/ledger.rs` fails when the appendix and the lock disagree.
"""
import json
import re
import subprocess
import sys

ROOT = subprocess.run(["cargo", "locate-project", "--workspace", "--message-format=plain"], capture_output=True, text=True, check=True).stdout.strip().rsplit("/", 1)[0]
POLICY = f"{ROOT}/docs/dependency-policy.md"
HEADING = "## Appendix — lock inventory"


def lock():
    out = {}
    name = ver = None
    for line in open(f"{ROOT}/Cargo.lock", encoding="utf-8"):
        line = line.strip()
        if line.startswith("name = "):
            name = line.split('"')[1]
        elif line.startswith("version = ") and name:
            ver = line.split('"')[1]
            out[name] = ver
            name = ver = None
    return out


def members():
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--no-deps"], capture_output=True, text=True, check=True, cwd=ROOT).stdout)
    return {p["name"]: p for p in meta["packages"]}


def tree(edges):
    """`cargo tree --workspace` rows as (depth, name) for the given edge kinds, every target."""
    out = subprocess.run(
        ["cargo", "tree", "--workspace", "-e", edges, "--target", "all", "--prefix", "depth", "--no-dedupe"],
        capture_output=True, text=True, cwd=ROOT, check=True,
    )
    rows = []
    for line in out.stdout.splitlines():
        m = re.match(r"^(\d+)([^ ]+) v(\S+)", line)
        if m:
            rows.append((int(m.group(1)), m.group(2)))
    return rows


def walk(rows, member_names):
    """crate -> set of '`direct dependency` via `member`' from one tree listing."""
    attrib = {}
    stack = []
    for depth, name in rows:
        del stack[depth:]
        stack.append(name)
        if depth == 0 or name in member_names:
            continue
        # the first non-member ancestor is the direct dependency; the member just above it is the one
        # whose manifest names it
        idx = next((i for i, n in enumerate(stack) if n not in member_names), len(stack) - 1)
        direct = stack[idx]
        member = next((n for n in reversed(stack[:idx]) if n in member_names), stack[0])
        attrib.setdefault(name, set()).add(f"`{direct}` via `{member}`")
    return attrib


def attribute(member_names):
    """Runtime and build edges first; crates that appear only through dev edges are marked dev-only,
    those that appear only through build edges build-only."""
    runtime = walk(tree("normal"), member_names)
    build = walk(tree("normal,build"), member_names)
    dev = walk(tree("normal,build,dev"), member_names)
    attrib = {}
    for name, vias in dev.items():
        if name in runtime:
            attrib[name] = runtime[name]
        elif name in build:
            attrib[name] = {f"{v} (build-only)" for v in build[name]}
        else:
            attrib[name] = {f"{v} (dev-only)" for v in vias}
    return attrib


def main():
    versions = lock()
    mem = members()
    attrib = attribute(set(mem))
    lines = [HEADING, "", "Generated by `python3 tools/spikes/lock-inventory.py` from `Cargo.lock` and `cargo tree`; the test",
             "`tools/pin-check/tests/ledger.rs` fails when this table and the lock disagree. A crate marked *dev-only* or",
             "*build-only* never ships in the binary; one marked *locked but never built* is in the lock because Cargo",
             "resolves optional dependencies of dependencies ahead of any feature choice, and is never compiled here.", "", f"{len([c for c in versions if c not in mem])} crates.", "",
             "| crate | version | enters through |", "|---|---|---|"]
    for name in sorted(versions):
        if name in mem:
            continue
        via = sorted(attrib.get(name, {"locked but never built: an optional dependency of a dependency that no feature of this workspace enables (still scanned by deny and audit)"}))
        runtime = [v for v in via if "-only)" not in v]
        via = runtime or via
        # keep the table readable: at most two attributions
        shown = "; ".join(via[:2]) + (f"; +{len(via)-2} more" if len(via) > 2 else "")
        lines.append(f"| `{name}` | {versions[name]} | {shown} |")
    text = open(POLICY, encoding="utf-8").read()
    head = text.split(HEADING)[0].rstrip() + "\n\n"
    open(POLICY, "w", encoding="utf-8").write(head + "\n".join(lines) + "\n")
    missing = [c for c in versions if c not in mem and c not in attrib]
    print(f"inventory: {len(lines) - 10} crates written to {POLICY}; unattributed: {missing}", file=sys.stderr)


if __name__ == "__main__":
    main()
